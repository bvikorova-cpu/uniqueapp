#!/usr/bin/env node
/**
 * Generates supabase/functions/_shared/uniCatalog.ts — a searchable catalog of
 * every static route in the app plus manual sub-feature aliases (categories,
 * tools, tabs) so Uni can find "mandala", "tajnicka", etc., not just top-level
 * sections.
 *
 * Usage: node scripts/generate-uni-catalog.mjs
 */
import fs from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";

const ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
const APP = path.join(ROOT, "src/App.tsx");
const OUT = path.join(ROOT, "supabase/functions/_shared/uniCatalog.ts");
const ALIASES = path.join(ROOT, "scripts/uni-catalog-aliases.json");

const src = fs.readFileSync(APP, "utf8");
const routes = new Set(["/"]);
const re = /<Route[^>]*\spath\s*=\s*["']([^"']+)["']/g;
let m;
while ((m = re.exec(src))) {
  const p = m[1].startsWith("/") ? m[1] : "/" + m[1];
  if (p.includes(":") || p.includes("*")) continue;
  if (p.startsWith("/__")) continue;
  routes.add(p);
}

function titleize(p) {
  if (p === "/") return "Home";
  return p
    .split("/")
    .filter(Boolean)
    .map((s) => s.replace(/-/g, " ").replace(/\b\w/g, (c) => c.toUpperCase()))
    .join(" — ");
}

const entries = [...routes].sort().map((p) => ({
  path: p,
  label: titleize(p),
  keywords: p.split(/[/-]/).filter(Boolean),
}));

const aliases = JSON.parse(fs.readFileSync(ALIASES, "utf8"));
for (const a of aliases) {
  entries.push({ path: a.path, label: a.label, keywords: a.keywords });
}

const header = `// AUTO-GENERATED by scripts/generate-uni-catalog.mjs — do not edit by hand.
// Searchable catalog of app destinations (routes + sub-features/categories).

export interface UniCatalogEntry {
  path: string;
  label: string;
  keywords: string[];
}

export const UNI_CATALOG: UniCatalogEntry[] = ${JSON.stringify(entries, null, 2)};

function norm(s: string): string {
  return s
    .toLowerCase()
    .normalize("NFD")
    .replace(/[\\u0300-\\u036f]/g, "")
    .replace(/[^a-z0-9 ]+/g, " ")
    .replace(/\\s+/g, " ")
    .trim();
}

/** Fuzzy keyword search over the whole catalog. Returns best matches first. */
export function searchCatalog(query: string, limit = 25): UniCatalogEntry[] {
  const q = norm(query);
  if (!q) return [];
  const tokens = q.split(" ").filter((t) => t.length > 2);
  const scored = UNI_CATALOG.map((e) => {
    const hay = norm([e.label, e.path, ...e.keywords].join(" "));
    let score = 0;
    for (const t of tokens) {
      if (hay.includes(t)) score += 3;
      else {
        const stem = t.slice(0, Math.max(4, t.length - 2));
        if (stem.length > 2 && hay.includes(stem)) score += 2;
      }
    }
    if (hay.includes(q)) score += 4;
    if (e.path.startsWith("/admin")) score -= 4;
    return { e, score };
  })
    .filter((r) => r.score > 0)
    .sort((a, b) => b.score - a.score)
    .slice(0, limit);
  return scored.map((r) => r.e);
}

/** True when the path exists in the catalog (allows query strings). */
export function isKnownPath(p: string): boolean {
  const base = p.split("?")[0];
  return UNI_CATALOG.some((e) => e.path.split("?")[0] === base);
}
`;

fs.mkdirSync(path.dirname(OUT), { recursive: true });
fs.writeFileSync(OUT, header);
console.log(`Wrote ${OUT} with ${entries.length} entries.`);
